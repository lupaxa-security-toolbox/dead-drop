"""Key sources. Passwords are never accepted as command-line arguments."""

from __future__ import annotations

import contextlib
import os
import stat
import struct
from dataclasses import dataclass
from pathlib import Path

from lupaxa.dead_drop.crypto.kdf import KdfParams, derive_key
from lupaxa.dead_drop.errors import ArgumentError, AuthenticationError, FilesystemError
from lupaxa.dead_drop.redact import register_secret, wipe

KEY_MAGIC = b"DDK1"
RAW_KIND = 1


@dataclass
class KeyMaterial:
    """A 32-byte key and a description of where it came from."""

    key: bytearray
    source: str
    kdf: KdfParams | None = None
    salt: bytes = b""
    warnings: list[str] | None = None

    def close(self) -> None:
        """Best-effort wipe of the local copy."""
        wipe(self.key)


def random_key() -> bytearray:
    """Draw 32 bytes from the operating system CSPRNG."""
    return bytearray(os.urandom(32))


def write_key_file(path: Path, key: bytes, *, force: bool) -> None:
    """Write a raw key file and warn that it must be protected."""
    if path.exists() and not force:
        raise FilesystemError(f"Key file already exists: {path}")
    payload = KEY_MAGIC + struct.pack(">B", RAW_KIND) + bytes(key)
    path.parent.mkdir(parents=True, exist_ok=True)
    flags = os.O_WRONLY | os.O_CREAT | (os.O_TRUNC if force else os.O_EXCL)
    descriptor = os.open(path, flags, 0o600)
    try:
        os.write(descriptor, payload)
    finally:
        os.close(descriptor)
    with contextlib.suppress(OSError):
        path.chmod(0o600)


def read_key_file(path: Path) -> bytearray:
    """Read a raw key file generated by Dead Drop."""
    blob = path.read_bytes()
    if len(blob) != len(KEY_MAGIC) + 1 + 32 or not blob.startswith(KEY_MAGIC):
        raise AuthenticationError("Authentication failed.")
    kind = blob[len(KEY_MAGIC)]
    if kind != RAW_KIND:
        raise AuthenticationError("Authentication failed.")
    key = bytearray(blob[-32:])
    register_secret(bytes(key).hex())
    return key


def read_password_file(path: Path) -> tuple[str, str]:
    """Read a password file and return the password plus a warning."""
    mode = path.stat().st_mode
    warning = (
        f"Password file {path} stores a reusable secret on disk. "
        "Prefer an interactive prompt or a randomly generated key file."
    )
    if mode & (stat.S_IRGRP | stat.S_IROTH):
        warning += " The file is readable by users other than the owner."
    text = path.read_text(encoding="utf-8").rstrip("\r\n")
    if not text:
        raise ArgumentError(f"Password file {path} is empty.")
    register_secret(text)
    return text, warning


def prompt_password(*, confirm: bool, non_interactive: bool) -> str:
    """Read a password without echoing it."""
    if non_interactive:
        raise ArgumentError("A password is required and prompts are disabled. Use a password file or key file.")
    import getpass

    password = getpass.getpass("Password: ")
    if confirm:
        again = getpass.getpass("Confirm password: ")
        if password != again:
            raise ArgumentError("Passwords did not match.")
    if password == "":
        raise ArgumentError("Password must not be empty.")
    register_secret(password)
    return password


def key_from_password(password: str, salt: bytes, params: KdfParams) -> KeyMaterial:
    """Derive key material from a password."""
    register_secret(password)
    raw = derive_key(password, salt, params)
    return KeyMaterial(key=bytearray(raw), source="password", kdf=params, salt=salt)
